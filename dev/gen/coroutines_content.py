# Sinh tracks/coroutines/content.vi.js và content.en.js từ MỘT nguồn (cùng cây khoá ở hai ngôn ngữ).
# Chạy: python dev/gen/coroutines_content.py   (công cụ phát triển, site không cần file này)
#
# Nguồn:
#  - dev/gen/coroutines_base.json: nội dung v1 (trích nguyên văn từ content.*.js ngày 2026-11-22, giữ đúng thứ tự khoá).
#    Sửa nội dung v1 ở đó.
#  - Nội dung v2 (chương dài, xem docs/chapter-template-v2.md) viết trong file này, sau phần nạp base.
# Kiểm tái tạo: chạy với base thuần cho ra đúng từng byte phần thân của content.*.js cũ (chỉ khác dòng chú thích đầu file).
import json, os, sys, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
P = 'track.coroutines.'
E = []
def a(k, vi, en=None): E.append((P + k, vi, vi if en is None else en))

with open(os.path.join(ROOT, 'dev', 'gen', 'coroutines_base.json'), encoding='utf-8') as f:
    for k, vi, en in json.load(f): E.append((k, vi, en))

# ---------------- v2 ----------------
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
def o(k, vi, en=None):
    """Ghi đè một chuỗi v1 đã có (giữ vị trí khoá)."""
    k = P + k
    for i, e in enumerate(E):
        if e[0] == k: E[i] = (k, vi, vi if en is None else en); return
    raise KeyError(k)

for mod in ('coroutines_v2_part1', 'coroutines_v2_u2', 'coroutines_v2_u3', 'coroutines_v2_u4', 'coroutines_v2_a3', 'coroutines_v2_a4', 'coroutines_v2_a2', 'coroutines_v2_a5', 'coroutines_v2_a6', 'coroutines_v2_sf', 'coroutines_v2_a4d', 'coroutines_v2_a8', 'coroutines_v2_a9', 'coroutines_v2_a9t', 'coroutines_v2_ch', 'coroutines_v2_fl', 'coroutines_v2_fb', 'coroutines_v2_fp', 'coroutines_v2_a7', 'coroutines_v2_a9f', 'coroutines_v2_pr'):
    if os.path.exists(os.path.join(here, mod + '.py')):
        mm = __import__(mod)
        mm.add(a)
        if hasattr(mm, 'override'): mm.override(o)
        # SEC_ORDER = {'<chương>': ['mục1', 'mục2', ...]}: sắp lại thứ tự các mục (v1 + v2) của chương; giữ vị trí khối khoá đầu tiên
        for ch, order in getattr(mm, 'SEC_ORDER', {}).items():
            pre = P + ch + '.sec.'
            idx = [i for i, e in enumerate(E) if e[0].startswith(pre)]
            items = [E[i] for i in idx]
            rank = lambda e: order.index(e[0][len(pre):].split('.')[0]) if e[0][len(pre):].split('.')[0] in order else len(order)
            items.sort(key=rank)   # sort ổn định: thứ tự trong cùng một mục được giữ
            first = idx[0]
            E[:] = [e for i, e in enumerate(E) if i not in set(idx)]
            E[first:first] = items

# ---------------- ghi file ----------------
def norm(s): return unicodedata.normalize('NFC', s)
keys = [k for k, _, _ in E]
seen = set(); dup = [k for k in keys if k in seen or seen.add(k)]
assert not dup, dup
HEAD = {'vi': '/* Nội dung track Kotlin Coroutines (tiếng Việt). SINH TỰ ĐỘNG từ dev/gen/coroutines_content.py: sửa ở đó rồi chạy lại. Cùng cây khoá với content.en.js. */',
        'en': '/* Content of the Kotlin Coroutines track (English). GENERATED by dev/gen/coroutines_content.py: edit there and re-run. Same key tree as content.vi.js. */'}
for lang, idx in (('vi', 1), ('en', 2)):
    body = ['  %s: %s' % (json.dumps(e[0]), json.dumps(norm(e[idx]), ensure_ascii=False)) for e in E]
    out = HEAD[lang] + '\n' + "ADE.addTrackStrings('coroutines', '%s', {\n" % lang + ',\n'.join(body) + '\n});\n'
    with open(os.path.join(ROOT, 'tracks', 'coroutines', 'content.%s.js' % lang), 'w', encoding='utf-8', newline='\n') as f: f.write(out)
print(len(E), 'keys')
